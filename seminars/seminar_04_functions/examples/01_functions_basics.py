# =============================================================================
# Определение и вызов функции
# =============================================================================
# Функция — это блок кода, которому дали имя. После определения его можно
# выполнять сколько угодно раз, обращаясь по этому имени.


def greet():
    print("Здравствуйте!")


# Определение функции само по себе ничего не выполняет.
# Чтобы код внутри заработал, функцию нужно ВЫЗВАТЬ — указать имя и скобки.
greet()
greet()

# =============================================================================
# Параметры и аргументы
# =============================================================================
# В скобках при определении перечисляют параметры — переменные, значения
# которых функция получит при вызове.


def greet_user(name):
    print(f"Здравствуйте, {name}!")


greet_user("Анна")
greet_user("Иван")

# Параметр — имя в определении функции (name).
# Аргумент — конкретное значение при вызове ("Анна").

# Параметров может быть несколько, порядок при вызове важен:


def print_student(name, group):
    print(f"{name} из группы {group}")


print_student("Анна", "Б01-123")

# =============================================================================
# return — вернуть результат
# =============================================================================
# print() показывает значение на экране, а return ОТДАЁТ его обратно в программу.
# Возвращённое значение можно сохранить в переменную и использовать дальше.


def rectangle_area(width, height):
    return width * height


area = rectangle_area(7, 4)
print("Площадь:", area)
print("Две площади:", rectangle_area(7, 4) * 2)

# Сравните: функция ниже только печатает и ничего не возвращает.


def print_rectangle_area(width, height):
    print(width * height)


result = print_rectangle_area(7, 4)
print("Что вернула функция без return:", result)  # None

# Функция без return (или с пустым return) возвращает None — «ничего».
# return также немедленно завершает работу функции:


def check_age(age):
    if age < 0:
        return "Возраст не может быть отрицательным"
    return "Возраст принят"


print(check_age(-5))
print(check_age(20))

# =============================================================================
# Докстринг — описание функции
# =============================================================================
# Первая строка в теле функции, записанная в тройных кавычках, объясняет,
# что функция делает. Это не комментарий: её можно прочитать через help().


def celsius_to_fahrenheit(celsius):
    """Перевести температуру из градусов Цельсия в градусы Фаренгейта."""
    return celsius * 9 / 5 + 32


print(celsius_to_fahrenheit(36.6))

# =============================================================================
