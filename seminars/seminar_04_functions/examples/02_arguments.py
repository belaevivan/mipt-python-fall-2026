"""Аргументы функций: позиционные, именованные и со значением по умолчанию.

Запуск:
    python seminars/seminar_04_functions/examples/02_arguments.py
"""


# =============================================================================
# Позиционные аргументы: важен порядок
# =============================================================================
def print_student(name, group):
    print(f"{name} из группы {group}")


print_student("Анна", "Б01-123")  # правильно
print_student("Б01-123", "Анна")  # значения перепутаны местами

# Если передать не то количество аргументов, будет ошибка:
# print_student("Анна")
# TypeError: print_student() missing 1 required positional argument: 'group'


# =============================================================================
# Именованные аргументы: порядок не важен
# =============================================================================
# При вызове можно указать, какому параметру какое значение передаётся.
# Так вызов читается понятнее, особенно когда аргументов много.

print_student(name="Анна", group="Б01-123")
print_student(group="Б01-123", name="Анна")  # тот же результат


# =============================================================================
# Значения по умолчанию
# =============================================================================
# Параметру можно задать значение, которое используется, если аргумент
# не передали при вызове.


def greet(name, greeting="Здравствуйте"):
    print(f"{greeting}, {name}!")


greet("Анна")  # Здравствуйте, Анна!
greet("Иван", "Привет")  # Привет, Иван!
greet("Пётр", greeting="Добрый день")  # понятнее, чем просто "Добрый день"


# Параметры со значением по умолчанию идут ПОСЛЕ обычных.
# Иначе Python не поймёт, какому параметру относится значение:
#
#   def greet(greeting="Привет", name):   # SyntaxError


# =============================================================================
# Пример: цена билета
# =============================================================================
# Задача с семинара 2, оформленная функцией.


def ticket_price(age, is_student=False):
    """Вернуть цену билета в рублях по возрасту и статусу студента."""
    if age < 7:
        return 0
    if age < 18:
        return 250
    if age >= 65:
        return 200
    if is_student:
        return 250
    return 450


print(ticket_price(5))
print(ticket_price(20))
print(ticket_price(20, is_student=True))
print(ticket_price(age=70))
