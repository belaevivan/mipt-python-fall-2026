"""Области видимости переменных и возврат нескольких значений.

Запуск:
    python seminars/seminar_04_functions/examples/03_scope_and_return.py
"""


# =============================================================================
# Локальные переменные
# =============================================================================
# Переменная, созданная внутри функции, существует только во время её работы.
# Снаружи её не видно.
def calculate_total(price, count):
    total = price * count  # локальная переменная
    return total


print(calculate_total(100, 3))

# print(total)
# NameError: name 'total' is not defined — переменная исчезла вместе с вызовом

# Параметры функции — тоже локальные переменные: price и count снаружи не существуют.


# =============================================================================
# Глобальные переменные
# =============================================================================
# Переменная, созданная вне функций, видна внутри них — её можно читать.

TAX_RATE = 0.2  # глобальная константа


def price_with_tax(price):
    return price * (1 + TAX_RATE)


print(price_with_tax(1000))


# =============================================================================
# Присваивание внутри функции не меняет глобальную переменную
# =============================================================================
counter = 0


def try_to_change():
    counter = 10  # создаётся НОВАЯ локальная переменная с тем же именем
    print("внутри функции:", counter)


try_to_change()
print("снаружи:", counter)  # 0 — глобальная переменная не изменилась


# Правильный способ изменить значение — вернуть его из функции:
def increased(value):
    return value + 1


counter = increased(counter)
print("после increased():", counter)  # 1

# В Python есть инструкция global, которая разрешает менять глобальную
# переменную изнутри функции, но пользоваться ей не стоит: функцию, которая
# незаметно меняет что-то снаружи, тяжело читать и отлаживать.


# =============================================================================
# Возврат нескольких значений
# =============================================================================
# После return можно перечислить несколько значений через запятую —
# функция вернёт кортеж (семинар 3).
def min_and_max(numbers):
    """Вернуть наименьшее и наибольшее число списка."""
    return min(numbers), max(numbers)


result = min_and_max([3, 14, 15, 9, 26])
print(result, type(result))  # (3, 26) <class 'tuple'>

# Обычно результат сразу распаковывают в отдельные переменные:
smallest, largest = min_and_max([3, 14, 15, 9, 26])
print("минимум:", smallest, "максимум:", largest)


# =============================================================================
# Распаковка со звёздочкой
# =============================================================================
# Звёздочка собирает «всё остальное» в список.

first, *rest = [1, 2, 3, 4, 5]
print(first, rest)  # 1 [2, 3, 4, 5]

*beginning, last = [1, 2, 3, 4, 5]
print(beginning, last)  # [1, 2, 3, 4] 5
