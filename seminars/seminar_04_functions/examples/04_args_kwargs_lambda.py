"""*args, **kwargs, функции как объекты и лямбда-функции.

Эти темы мы не разбираем на семинаре — примеры для самостоятельного изучения.

Запуск:
    python seminars/seminar_04_functions/examples/04_args_kwargs_lambda.py
"""


# =============================================================================
# *args — произвольное число позиционных аргументов
# =============================================================================
# Звёздочка перед именем параметра означает: «собери все оставшиеся
# позиционные аргументы в кортеж».
def sum_all(*numbers):
    """Сложить любое количество переданных чисел."""
    total = 0
    for number in numbers:
        total += number
    return total


print(sum_all(1, 2))
print(sum_all(1, 2, 3, 4, 5))
print(sum_all())  # 0 — аргументов нет, кортеж пустой

# Имя args — просто соглашение, работает любое: *numbers, *values.

# Обратная операция — распаковать готовый список в аргументы функции:
values = [1, 2, 3]
print(sum_all(*values))  # то же самое, что sum_all(1, 2, 3)


# =============================================================================
# **kwargs — произвольное число именованных аргументов
# =============================================================================
# Две звёздочки собирают именованные аргументы в словарь (семинар 3).
def build_profile(name, **extra):
    """Собрать словарь с данными пользователя."""
    profile = {"name": name}
    for key, value in extra.items():
        profile[key] = value
    return profile


print(build_profile("Анна"))
print(build_profile("Иван", group="Б01-123", course=1))


# =============================================================================
# Функции — это объекты
# =============================================================================
# Функцию можно присвоить переменной и передать в другую функцию как аргумент.
def double(number):
    return number * 2


operation = double  # без скобок — это сама функция, а не её вызов
print(operation(21))


def apply_to_all(function, items):
    """Применить функцию к каждому элементу списка."""
    result = []
    for item in items:
        result.append(function(item))
    return result


print(apply_to_all(double, [1, 2, 3]))

# Функция, принимающая другую функцию (или возвращающая её),
# называется функцией высшего порядка.


# =============================================================================
# Лямбда-функции
# =============================================================================
# lambda — короткая безымянная функция из одного выражения.
# Результат этого выражения возвращается автоматически, без return.
#
#   lambda аргументы: выражение
#
# Лямбды пишут там, где функция нужна «на один раз» — обычно её передают
# в другую функцию.

words = ["питон", "код", "программирование", "файл"]
print(sorted(words, key=lambda word: len(word)))  # сортировка по длине слова

numbers = [1, 2, 3, 4, 5, 6]
print(list(filter(lambda number: number % 2 == 0, numbers)))  # только чётные
print(list(map(double, numbers)))  # применить функцию к каждому элементу

# filter(функция, коллекция) — оставляет элементы, для которых функция даёт True
# map(функция, коллекция)    — применяет функцию к каждому элементу
# Обе возвращают не список, а специальный объект, поэтому его оборачивают в list().

# Присваивать лямбду переменной не стоит — линтеры на это ругаются (ошибка E731):
#
#   square = lambda number: number**2      # так не надо
#   def square(number): return number**2   # так понятнее
#
# И почти всегда то же самое короче записывается списочным выражением (семинар 3):

print([number for number in numbers if number % 2 == 0])  # вместо filter()
print([double(number) for number in numbers])  # вместо map()
