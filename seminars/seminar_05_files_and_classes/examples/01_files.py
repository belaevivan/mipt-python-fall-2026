"""Работа с файлами: чтение и запись.

Запускать из папки семинара, чтобы сработали относительные пути:
    cd seminars/seminar_05_files_and_classes
    python examples/01_files.py
"""

# =============================================================================
# Зачем нужны файлы
# =============================================================================
# Все переменные исчезают, когда программа заканчивает работу. Файл позволяет
# сохранить данные на диск и прочитать их при следующем запуске.

# =============================================================================
# open() и with
# =============================================================================
# open(путь, режим, encoding) открывает файл. Открытый файл нужно закрыть,
# иначе данные могут не записаться, а сам файл останется занятым.
#
# Конструкция with закрывает файл автоматически — даже если внутри произошла
# ошибка. Поэтому файлы всегда открывают через with.

with open("data/cities.txt", encoding="utf-8") as file:
    content = file.read()  # весь файл одной строкой

print(content)

# encoding="utf-8" указывают всегда: без него русский текст на Windows
# может прочитаться неправильно.

# =============================================================================
# Режимы открытия
# =============================================================================
#   "r" — чтение; это режим по умолчанию, поэтому его обычно не пишут,
#         если файла нет -> FileNotFoundError
#   "w" — запись; файл создаётся, а существующий ОЧИЩАЕТСЯ
#   "a" — дозапись в конец; файл создаётся, если его нет

# =============================================================================
# Три способа прочитать файл
# =============================================================================

# 1. read() — всё содержимое одной строкой
with open("data/cities.txt", encoding="utf-8") as file:
    text = file.read()

print("Символов в файле:", len(text))

# 2. readlines() — список строк
with open("data/cities.txt", encoding="utf-8") as file:
    lines = file.readlines()

print("Строк в файле:", len(lines))
print("Первая строка:", lines[0])  # в конце строки остался символ переноса

# 3. Перебор файла циклом — самый частый способ: строки читаются по одной
#    и не занимают память целиком
with open("data/cities.txt", encoding="utf-8") as file:
    for line in file:
        print("Город:", line.strip())  # strip() убирает перенос строки и пробелы

# =============================================================================
# Разбор строк с данными
# =============================================================================
# В файле menu.txt каждая строка — «название;цена». Такие строки разбирают
# методом split() (семинар 3).

total = 0
with open("data/menu.txt", encoding="utf-8") as file:
    for line in file:
        name, price = line.strip().split(";")
        print(f"{name} — {price} руб.")
        total += int(price)

print("Сумма всех цен:", total)

# =============================================================================
# Запись в файл
# =============================================================================
# write() записывает строку и НЕ добавляет перенос строки — его ставят сами.

with open("output.txt", "w", encoding="utf-8") as file:
    file.write("Отчёт о работе\n")
    file.write("=" * 20 + "\n")
    for number in range(1, 4):
        file.write(f"Строка номер {number}\n")

print("Файл output.txt записан")

# Режим "a" дописывает в конец, не стирая то, что было:
with open("output.txt", "a", encoding="utf-8") as file:
    file.write("Добавлено позже\n")

with open("output.txt", encoding="utf-8") as file:
    print(file.read())

# write() принимает только строки: число нужно превратить в строку
# через str() или f-строку.

# =============================================================================
# Если файла нет
# =============================================================================
