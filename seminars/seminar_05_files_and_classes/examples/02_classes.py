"""Классы и объекты: class, __init__, self, атрибуты.

Запуск:
    python seminars/seminar_05_files_and_classes/examples/02_classes.py
"""

# =============================================================================
# С чего всё начинается: данные отдельно, функции отдельно
# =============================================================================
# Опишем книгу тем, что уже знаем — словарём (семинар 3) и функциями (семинар 4).

book = {"title": "Евгений Онегин", "author": "Пушкин", "year": 1833}


def describe_book(data):
    return f"{data['title']} — {data['author']}, {data['year']}"


print(describe_book(book))

# Это работает, но у такого подхода есть проблемы:
#   - ничто не мешает создать словарь без ключа "year" или с опечаткой в ключе;
#   - функция describe_book живёт отдельно от данных, о связи знает только автор;
#   - когда таких сущностей десятки, в коде тяжело найти, что к чему относится.

# =============================================================================
# Класс — описание сущности
# =============================================================================
# Класс объединяет данные (атрибуты) и действия над ними (методы).
#
#   Класс    — чертёж, описание: что у сущности есть и что она умеет.
#   Объект   — конкретный экземпляр, созданный по этому чертежу.
#
# Класс «Книга» один, а объектов-книг может быть сколько угодно.


class Book:
    """Книга в библиотеке."""

    def __init__(self, title, author, year):
        self.title = title
        self.author = author
        self.year = year


# Создание объекта выглядит как вызов класса:
first = Book("Евгений Онегин", "Пушкин", 1833)
second = Book("Мастер и Маргарита", "Булгаков", 1967)

print(first.title)  # обращение к атрибуту через точку
print(second.author)

# =============================================================================
# __init__ и self
# =============================================================================
# __init__ — конструктор: метод, который Python вызывает автоматически
# при создании объекта. В нём задают начальные атрибуты.
#
# self — ссылка на сам создаваемый объект. Он всегда идёт первым параметром,
# но при вызове его НЕ передают: Book("...", "...", 1833) — три аргумента,
# а в __init__ их четыре вместе с self.
#
#   self.title = title
#   ^^^^^^^^^^   ^^^^^
#   атрибут      параметр
#   объекта      метода

# У каждого объекта свои значения атрибутов — они независимы:
first.year = 2024
print(first.year, second.year)  # 2024 1967

# Атрибут можно добавить и после создания, но так лучше не делать:
# все атрибуты объявляют в __init__, чтобы было видно, из чего состоит объект.

# =============================================================================
# Объекты в коллекциях
# =============================================================================
# Объекты — обычные значения: их можно складывать в списки и перебирать циклом.

library = [
    Book("Евгений Онегин", "Пушкин", 1833),
    Book("Мастер и Маргарита", "Булгаков", 1967),
    Book("Преступление и наказание", "Достоевский", 1866),
]

for book in library:
    print(f"{book.title} ({book.year})")

# Сортировка списка объектов по атрибуту (лямбда — семинар 4):
for book in sorted(library, key=lambda item: item.year):
    print(book.year, book.title)

print(type(first))  # <class '__main__.Book'>
