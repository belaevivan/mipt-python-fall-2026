# =============================================================================
# Метод — функция внутри класса
# =============================================================================
# Метод описывают как обычную функцию, но внутри класса и с параметром self
# на первом месте. Через self метод получает доступ к атрибутам объекта.
class Rectangle:
    """Прямоугольник."""

    def __init__(self, width, height):
        self.width = width
        self.height = height

    def area(self):
        """Вернуть площадь прямоугольника."""
        return self.width * self.height

    def perimeter(self):
        """Вернуть периметр прямоугольника."""
        return (self.width + self.height) * 2


first = Rectangle(7, 4)
print(first.area())  # 28
print(first.perimeter())  # 22

# Вызов first.area() — это способ записи: Python сам подставляет first
# в параметр self. Поэтому в скобках пусто, хотя в определении метода
# есть параметр.

# Метод может принимать и обычные аргументы — они идут после self:


class Greeter:
    def __init__(self, name):
        self.name = name

    def greet(self, greeting="Здравствуйте"):
        return f"{greeting}, {self.name}!"


print(Greeter("Анна").greet())
print(Greeter("Иван").greet("Привет"))


# =============================================================================
# Состояние объекта: методы, которые меняют атрибуты
# =============================================================================
# Пока методы только читали атрибуты. Но метод может их и изменять —
# тогда говорят, что объект меняет своё состояние.
class ShoppingCart:
    """Корзина покупок."""

    def __init__(self):
        self.items = []  # у каждой корзины свой список

    def add_item(self, name, price):
        """Добавить товар в корзину."""
        self.items.append((name, price))

    def total(self):
        """Вернуть общую стоимость товаров."""
        result = 0
        # подчёркивание вместо имени означает: это значение здесь не нужно
        for _, price in self.items:
            result += price
        return result

    def count(self):
        """Вернуть количество товаров."""
        return len(self.items)


cart = ShoppingCart()
cart.add_item("кофе", 180)
cart.add_item("чай", 120)

print("Товаров:", cart.count())
print("Итого:", cart.total())

# Сравните с семинаром 4: там функция не могла изменить глобальную переменную
# и приходилось возвращать новое значение. Объект хранит состояние внутри себя,
# поэтому метод может просто его обновить.

other_cart = ShoppingCart()
print("Товаров во второй корзине:", other_cart.count())  # 0 — объекты независимы


# =============================================================================
# Инкапсуляция: менять состояние только через методы
# =============================================================================
# Инкапсуляция — это идея «данные внутри, доступ снаружи только через методы».
# Методы следят за тем, чтобы объект не оказался в некорректном состоянии.
class BankAccount:
    """Банковский счёт."""

    def __init__(self, owner):
        self.owner = owner
        self._balance = 0  # подчёркивание означает «не трогать снаружи»

    def deposit(self, amount):
        """Пополнить счёт."""
        if amount <= 0:
            print("Сумма пополнения должна быть больше нуля")
            return
        self._balance += amount

    def withdraw(self, amount):
        """Снять деньги со счёта, если их хватает."""
        if amount > self._balance:
            print("Недостаточно средств")
            return
        self._balance -= amount

    def balance(self):
        """Вернуть текущий баланс."""
        return self._balance


account = BankAccount("Анна")
account.deposit(1000)
account.withdraw(300)
account.withdraw(5000)  # не хватит денег — метод не даст уйти в минус
print("Баланс:", account.balance())

# Если бы баланс меняли напрямую (account.balance = -5000), проверку обойти
# было бы легко. В Python нет настоящих «закрытых» атрибутов: подчёркивание —
# это соглашение между программистами, а не запрет.
